# Política de cookies

@include('legal.es._titular')

**Solo usamos cookies técnicas**, imprescindibles para que la web funcione. No usamos cookies de analítica, publicidad ni redes sociales, y por eso no te pedimos consentimiento.

| Cookie | Para qué | Duración |
| --- | --- | --- |
| `{{ $cookieSesion }}` | Mantener tu sesión: el carrito, tus diseños y, si entras, tu cuenta | Mientras navegas y unas horas después |
| `XSRF-TOKEN` | Proteger los formularios frente a envíos falsos | Igual que la sesión |
| `{{ $cookieCarrito }}` | Recordar tu carrito si vuelves sin cuenta | Los días que se guarda el carrito |

Al pagar sales a la página de Redsys, que tiene su propia política de cookies.

Si algún día añadimos cookies que no sean técnicas, te pediremos permiso antes de usarlas y lo indicaremos aquí.
