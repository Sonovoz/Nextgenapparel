# Cookie policy

@include('legal.en._titular')

**We only use technical cookies**, which the website needs to work. We use no analytics, advertising or social media cookies, so we do not ask for your consent.

| Cookie | Purpose | Duration |
| --- | --- | --- |
| `{{ $cookieSesion }}` | Keeping your session: the cart, your designs and, if you sign in, your account | While you browse and a few hours after |
| `XSRF-TOKEN` | Protecting forms against forged submissions | Same as the session |
| `{{ $cookieCarrito }}` | Remembering your cart if you come back without an account | The days the cart is kept |

When you pay you go to the Redsys page, which has its own cookie policy.

If we ever add non-technical cookies, we will ask for your permission first and say so here.
